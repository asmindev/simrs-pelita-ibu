<?php

namespace App\Console\Commands;

use App\Enums\RoleName;
use App\Support\PermissionRegistry;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

#[Signature('simrs:permissions {--types : Generate TypeScript permission and role types}')]
#[Description('List SIMRS permissions or generate TypeScript type definitions')]
class GeneratePermissionTypes extends Command
{
    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $permissions = PermissionRegistry::all();
        sort($permissions);

        if (! $this->option('types')) {
            $this->components->info(count($permissions).' permissions');

            foreach (PermissionRegistry::byDomain() as $domain => $items) {
                $this->line(" {$domain}: ".count($items));
            }

            return self::SUCCESS;
        }

        $roles = array_map(
            fn (RoleName $role): string => $role->value,
            RoleName::cases(),
        );
        sort($roles);

        $content = $this->types($permissions, $roles);
        $path = resource_path('js/types/permissions.d.ts');

        File::put($path, $content);

        $this->components->info("Generated {$path}");

        return self::SUCCESS;
    }

    /**
     * @param  array<int, string>  $permissions
     * @param  array<int, string>  $roles
     */
    private function types(array $permissions, array $roles): string
    {
        $permissionLines = array_map(
            fn (string $permission): string => "    | '{$this->escape($permission)}'",
            $permissions,
        );
        $roleLines = array_map(
            fn (string $role): string => "    | '{$this->escape($role)}'",
            $roles,
        );

        return implode("\n", [
            '// This file is generated by `php artisan simrs:permissions --types`.',
            'export type PermissionName =',
            implode("\n", $permissionLines).';',
            '',
            'export type RoleName =',
            implode("\n", $roleLines).';',
            '',
        ]);
    }

    private function escape(string $value): string
    {
        return str_replace("'", "\\'", $value);
    }
}
